export const brandComparisons: {
  brand: string;
  map: Record<string, string>;
}[] = [
  { brand: "COS", map: { XS: "S", S: "M", M: "L", L: "XL" } },
  { brand: "Acne Studios", map: { "32": "S", "34": "M", "36": "L", "38": "XL" } },
  {
    brand: "Levi's",
    map: { "26": "XS", "28": "S", "30": "M", "32": "L", "34": "XL" },
  },
  {
    brand: "Everlane",
    map: { "00": "XXS", "0": "XS", "2": "S", "4": "S", "6": "M", "8": "L" },
  },
];

export function predictSableSize(brand: string, theirSize: string) {
  const row = brandComparisons.find((item) => item.brand === brand);
  return row?.map[theirSize] ?? "M";
}
